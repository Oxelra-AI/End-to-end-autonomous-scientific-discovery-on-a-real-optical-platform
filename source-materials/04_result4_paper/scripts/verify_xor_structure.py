#!/usr/bin/env python3
"""
Verify that Task B has XOR/parity structure making it linearly
inseparable from [z(x),z(y)] concat features.
"""
import numpy as np

print("=== MATHEMATICAL ANALYSIS ===")
print()
print("Task B label matrix (x=row, y=col):")
pos = {(0,1),(1,2),(2,3),(3,0),(1,0),(2,1),(3,2),(0,3)}
labels = np.zeros((4,4), dtype=int)
for x in range(4):
    for y in range(4):
        labels[x,y] = 1 if (x,y) in pos else 0
print(labels)
print()

check = np.array([[(x+y)%2 for y in range(4)] for x in range(4)])
print(f"Matches (x+y)%2 checkerboard: {np.all(labels == check)}")
print()

print("=== LINEAR READOUT LIMIT FOR [z(x),z(y)] ON THIS PARITY TASK ===")
print()
print("A linear classifier on [z(x),z(y)] computes:")
print("  f(x,y) = a^T z(x) + b^T z(y) + c")
print()
print("For this to predict (x+y)%2, consider the constraints:")
print()
print("From x=0 row:")
print("  a^T z(0) + b^T z(1) must be positive (label=1)")
print("  a^T z(0) + b^T z(3) must be positive (label=1)")
print("  a^T z(0) + b^T z(0) must be negative (label=0)")
print("  a^T z(0) + b^T z(2) must be negative (label=0)")
print("  ==> b must rank z(1),z(3) higher than z(0),z(2)")
print()
print("From x=1 row:")
print("  a^T z(1) + b^T z(0) must be positive (label=1)")
print("  a^T z(1) + b^T z(2) must be positive (label=1)")
print("  a^T z(1) + b^T z(1) must be negative (label=0)")
print("  a^T z(1) + b^T z(3) must be negative (label=0)")
print("  ==> b must rank z(0),z(2) higher than z(1),z(3)")
print()
print("The two row-wise constraints require incompatible rankings of the y-token scores:")
print("b cannot simultaneously rank {1,3} above {0,2}")
print("AND rank {0,2} above {1,3}.")
print()
print("This is the standard XOR/parity structure.")
print("The relation (x+y)%2 is nonlinear in separate token identities.")
print("An additive linear readout from concatenated features is therefore")
print("not an appropriate baseline for this relation unless interaction")
print("features are also supplied.")
print()
print("=== WHY PHYSICAL B(x,y) CAN SOLVE IT ===")
print()
print("B(x,y) = conj(T*E_x) * (T*E_y) is a BILINEAR function.")
print("It physically computes a product-like interaction term.")
print("The parity (x+y)%2 can be expressed as a function of products.")
print("Therefore B(x,y) encodes the interaction information that")
print("linear readout from separate tokens does not include.")
print()
print("Similarly, digital bilinear z(x)*z(y) can solve Task B")
print("because elementwise products are also bilinear.")
print("But digital bilinear LOSES pair identity (Task A fails)")
print("because the product is symmetric and compresses identity info.")
print()
print("=== WHY DIGITAL BILINEAR FAILS TASK A ===")
print()
print("z(x)*z(y) is elementwise: feature_j = z_j(x) * z_j(y)")
print("This is SYMMETRIC in a specific sense: the product of two")
print("different-identity tokens can collide if their channel values")
print("happen to produce similar products.")
print("More critically, with only 400 product features from averaged")
print("single-token embeddings, the 16-class pair identity is hard")
print("because the product collapses directional identity information.")
print()
print("=== SUMMARY ===")
print()
print("The compressed-budget comparison separates three feature families:")
print("1. [z(x),z(y)] concat: solves identity (Task A) but does not")
print("   include the interaction terms needed for the parity relation")
print("   under an additive linear readout.")
print("2. Digital bilinear z(x)*z(y): solves relation (Task B) but")
print("   loses identity resolution (Task A stuck at 0.25).")
print("3. Physical B(x,y): solves both tested tasks because scattering-mediated")
print("   coherent cross-term preserves both identity and interaction")
print("   information in a single compact observable.")
print()
print("This script supports the claim that the measured bilinear field")
print("contains interaction information that is absent from the separate-token")
print("linear baseline for this designed parity task.")
